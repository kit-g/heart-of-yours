/// Writes the Siri phrases and the titles beside the Runner's Info.plist. The
/// English value is the key, since that is what the Swift source says; the
/// other base languages are its localizations, and regional locales inherit
/// the base language.
///
/// Two formats, because the App Shortcuts metadata processor accepts the
/// phrases only as `<lang>.lproj/AppShortcuts.strings` on a deployment target
/// below iOS 17; the titles are an ordinary `Localizable.xcstrings`.
void writeIosStringCatalogs(Map<String, Map<String, dynamic>> translations, Directory runner) {
  File('${runner.path}/Localizable.xcstrings').writeAsStringSync(stringCatalog(translations, runnerShortcutTitleKeys));
  final languages = translations.keys.where((locale) => !locale.contains('_')).toList()..sort();
  for (final language in languages) {
    final directory = Directory('${runner.path}/$language.lproj')..createSync(recursive: true);
    File('${directory.path}/AppShortcuts.strings').writeAsStringSync(
      stringsTable(translations, runnerShortcutPhraseKeys, language),
    );
  }
}

/// A `.strings` table for [keys] in [language], keyed by the English value.
String stringsTable(Map<String, Map<String, dynamic>> translations, List<String> keys, String language) {
  final lines = keys.map((key) {
    final english = translations['en']?[key];
    if (english is! String || english.trim().isEmpty) {
      throw StateError('Missing English iOS shortcut translation: $key');
    }
    final value = translations[language]?[key];
    if (value is! String || value.trim().isEmpty) {
      throw StateError('Missing iOS shortcut translation: $language/$key');
    }
    return '${_quoted(english)} = ${_quoted(value)};';
  });
  return '// Generated by heart_language translation import. Do not edit.\n${lines.join('\n')}\n';
}

/// A `.xcstrings` catalog for [keys]: Xcode's JSON, sorted, two-space indented.
String stringCatalog(Map<String, Map<String, dynamic>> translations, List<String> keys) {
  final languages = translations.keys.where((locale) => !locale.contains('_') && locale != 'en').toList()..sort();
  final strings = <String, Object>{};
  for (final key in keys) {
    final english = translations['en']?[key];
    if (english is! String || english.trim().isEmpty) {
      throw StateError('Missing English iOS shortcut translation: $key');
    }
    final localizations = <String, Object>{};
    for (final language in languages) {
      final value = translations[language]![key];
      if (value is! String || value.trim().isEmpty) {
        throw StateError('Missing iOS shortcut translation: $language/$key');
      }
      localizations[language] = {
        'stringUnit': {'state': 'translated', 'value': value},
      };
    }
    strings[english] = {'localizations': localizations};
  }
  final catalog = {
    'sourceLanguage': 'en',
    'strings': {for (final key in strings.keys.toList()..sort()) key: strings[key]},
    'version': '1.0',
  };
  return '${const JsonEncoder.withIndent('  ').convert(catalog)}\n';
}
